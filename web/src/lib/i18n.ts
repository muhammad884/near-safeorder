function pick(): Lang {
  try {
    const s = localStorage.getItem('so-lang');
    if (s === 'en' || s === 'ha') return s;
  } catch { /* ignore */ }
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ha') ? 'ha' : 'en';
}
let lang: Lang = pick();
const subs = new Set<() => void>();
export function setLang(l: Lang) {
  lang = l;
  try { localStorage.setItem('so-lang', l); } catch { /* ignore */ }
  document.documentElement.lang = l;
  subs.forEach((f) => f());
}
function tr(l: Lang, k: string, v?: Record<string, string | number>) {
  const e = D[k];
  let s = e ? e[l === 'ha' ? 1 : 0] : k;
  if (v) for (const x of Object.keys(v)) s = s.split('{' + x + '}').join(String(v[x]));
  return s;
}
export function useT() {
  const l = useSyncExternalStore((cb) => { subs.add(cb); return () => { subs.delete(cb); }; }, () => lang);
  return {
    lang: l,
    t: (k: string, v?: Record<string, string | number>) => tr(l, k, v),
    act: (a: string) => D['act.' + a]?.[l === 'ha' ? 1 : 0] ?? a,
  };
}
